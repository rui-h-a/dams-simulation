"""LaTeX macros of the 10,000-member main study from its pooled raw-admitted report.

Input: 04_evaluation/r11/main-n10000/pooled.json and roster.json (collect_study.py). Output:
05_thesis/generated/r11_main_macros.tex with one macro per arm and endpoint (mean, interval bounds, Holm p,
worlds) and the roster counts. Missing comparisons produce no macro, so the text cannot cite an absent value.
Usage: python 04_evaluation/r11/make_main_macros.py
"""
import json
from pathlib import Path

R = Path(__file__).resolve().parent
OUT = R.parents[1]/'05_thesis'/'generated'/'r11_main_macros.tex'
ARMS = {'control-process': 'Proc', 'dams-witness': 'Dams', 'linear-witness': 'Lin'}
KEYS = {'net_operating_result_per_member_year': ('Net', 1, '{:.1f}'),
        'decision_regret_per_available_member_hour': ('Regret', 1e6, '{:.2f}'),
        'governance_member_hours_per_member_year': ('Gov', 1, '{:.2f}'),
        'witness_resource_units_per_member_year': ('Wit', 1, '{:.1f}'),
        'confirmation_mean_days': ('Conf', 1, '{:.1f}'),
        'output_per_available_member_hour': ('Output', 1, '{:.4f}')}


def fmt(v, f):
    return f.format(v).replace('-', '$-$')


def main():
    pooled = json.loads((R/'main-n10000'/'pooled.json').read_text())
    roster = json.loads((R/'main-n10000'/'roster.json').read_text())
    lines = ['% generated by 04_evaluation/r11/make_main_macros.py; do not edit',
             f"\\newcommand{{\\MainWorlds}}{{{len(roster['finished'])}}}",
             f"\\newcommand{{\\MainAssigned}}{{{len(roster['assigned'])}}}"]
    for arm, a in ARMS.items():
        for key, (k, scale, f) in KEYS.items():
            r = pooled['comparisons'].get(arm, {}).get(key)
            if not r or r.get('mean_difference') is None:
                continue
            m, (lo, hi) = r['mean_difference']*scale, (v*scale for v in r['ci95'])
            lines += [f"\\newcommand{{\\Main{a}{k}}}{{{fmt(m, f)}}}",
                      f"\\newcommand{{\\Main{a}{k}CI}}{{[{fmt(lo, f)}, {fmt(hi, f)}]}}"]
            if r.get('p_holm') is not None:
                lines.append(f"\\newcommand{{\\Main{a}{k}P}}{{{r['p_holm']:.1g}}}")
    OUT.write_text('\n'.join(lines)+'\n')
    print('written', OUT, len(lines)-3, 'macros')


if __name__ == '__main__':
    main()
